-- The compact record format (Phase 3); see the SQLite migration of the same
-- name for the columns. Postgres keeps record as TEXT: byte-exact (JSONB
-- normalises key order and whitespace), decodable by sqlx's Any driver, and
-- readable from raw SQL with ->> and expression indexes as before.

CREATE TABLE IF NOT EXISTS happyview_dids (
    id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    did TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS happyview_collections (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nsid TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS happyview_records_v2 (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    did_id        BIGINT NOT NULL REFERENCES happyview_dids(id),
    collection_id BIGINT NOT NULL REFERENCES happyview_collections(id),
    rkey          TEXT NOT NULL,
    cid           BYTEA NOT NULL,
    record        TEXT NOT NULL,
    rev           TEXT,
    indexed_at    BIGINT,
    created_at    BIGINT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_records_v2_identity
    ON happyview_records_v2 (did_id, collection_id, rkey);
CREATE INDEX IF NOT EXISTS idx_records_v2_collection_indexed_at
    ON happyview_records_v2 (collection_id, indexed_at);
CREATE INDEX IF NOT EXISTS idx_records_v2_collection_created_at_id
    ON happyview_records_v2 (collection_id, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS happyview_record_refs_v2 (
    source_id            BIGINT NOT NULL REFERENCES happyview_records_v2(id) ON DELETE CASCADE,
    target_did_id        BIGINT NOT NULL,
    target_collection_id BIGINT NOT NULL,
    target_rkey          TEXT NOT NULL,
    collection_id        BIGINT NOT NULL,
    PRIMARY KEY (source_id, target_did_id, target_collection_id, target_rkey)
);

CREATE INDEX IF NOT EXISTS idx_record_refs_v2_target
    ON happyview_record_refs_v2 (target_did_id, target_collection_id, target_rkey, collection_id);

-- lz4 is faster than the default pglz and compresses bodies big enough to be
-- toasted (over about 2 KB); post-sized rows are never toasted, whatever
-- toast_tuple_target says (measured 2026-10-11), so that is left alone. A
-- server built without lz4 refuses the method (feature_not_supported), one
-- older than Postgres 14 the syntax (syntax_error); either keeps the default
-- and says so rather than failing the migration.
DO $$
BEGIN
    EXECUTE 'ALTER TABLE happyview_records_v2 ALTER COLUMN record SET COMPRESSION lz4';
EXCEPTION WHEN feature_not_supported OR invalid_parameter_value OR syntax_error THEN
    RAISE NOTICE 'lz4 is unavailable; happyview_records_v2.record keeps the default compression';
END $$;
